-- ===== Productos =====
create table if not exists public.productos (
  id            bigint generated by default as identity primary key,
  categoria     text not null references public.secciones(id) on update cascade on delete restrict,
  nombre        text not null,
  descripcion   text not null default '',
  precio        numeric(10,2) check (precio is null or precio >= 0),        -- null = «Precio por confirmar»
  precio_oferta numeric(10,2),
  imagenes      text[] not null default '{}',                              -- la primera es la principal
  nuevo         boolean not null default false,
  visible       boolean not null default true,
  orden         integer not null default 0,
  creado        timestamptz not null default now(),
  actualizado   timestamptz not null default now(),
  constraint oferta_valida check (precio_oferta is null or (precio_oferta >= 0 and precio is not null and precio_oferta < precio))
);

drop trigger if exists productos_actualizado on public.productos;
create trigger productos_actualizado before update on public.productos
for each row execute function public.tocar_actualizado();

alter table public.productos enable row level security;
drop policy if exists "ver productos"    on public.productos;
drop policy if exists "crear productos"  on public.productos;
drop policy if exists "editar productos" on public.productos;
drop policy if exists "borrar productos" on public.productos;
create policy "ver productos" on public.productos for select to anon, authenticated using (visible or public.es_admin());
create policy "crear productos" on public.productos for insert to authenticated with check (public.es_admin());
create policy "editar productos" on public.productos for update to authenticated using (public.es_admin()) with check (public.es_admin());
create policy "borrar productos" on public.productos for delete to authenticated using (public.es_admin());
grant select on public.productos to anon, authenticated;
grant insert, update, delete on public.productos to authenticated;
grant usage, select on sequence public.productos_id_seq to authenticated;

