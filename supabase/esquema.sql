create or replace function public.crear_cotizacion(p jsonb) returns bigint
language plpgsql security definer set search_path = '' as $$
declare v_num bigint;
begin
  if coalesce(trim(p->>'cliente'), '') = '' or coalesce(trim(p->>'telefono'), '') = '' then
    raise exception 'Faltan el nombre o el teléfono';
  end if;
  insert into public.cotizaciones (cliente, telefono, tipo, fecha_evento, lugar, invitados, servicios,
                                   estilo, presupuesto, referencia, detalles)
  values (
    left(trim(p->>'cliente'), 120),
    left(trim(p->>'telefono'), 40),
    left(coalesce(nullif(trim(p->>'tipo'), ''), 'Otro'), 60),
    nullif(p->>'fecha', '')::date,
    left(p->>'lugar', 200),
    nullif(p->>'invitados', '')::integer,
    coalesce((select array_agg(left(x, 60)) from (select jsonb_array_elements_text(p->'servicios') x limit 20) s), '{}'),
    left(p->>'estilo', 300),
    left(p->>'presupuesto', 60),
    left(p->>'referencia', 200),
    left(p->>'detalles', 1500)
  )
  returning numero into v_num;
  return v_num;
end $$;

revoke all on function public.crear_cotizacion(jsonb) from public;
grant execute on function public.crear_cotizacion(jsonb) to anon, authenticated;

