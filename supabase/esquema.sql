-- ===== Pedidos =====
create table if not exists public.pedidos (
  numero      bigint generated always as identity primary key,
  creado      timestamptz not null default now(),
  estado      text not null default 'pendiente'
              check (estado in ('pendiente','confirmado','en_preparacion','listo','entregado','cancelado')),
  cliente     text not null,
  telefono    text not null,
  entrega     text not null check (entrega in ('delivery','pickup')),
  direccion   text,
  fecha       date,
  hora        text,
  metodo      text not null default '',
  items       jsonb not null,             -- [{id, nombre, precio, q}]
  total       numeric(10,2) not null,
  tarjeta     text,                       -- mensaje para la tarjeta
  nota        text,
  notas_admin text,
  actualizado timestamptz not null default now()
);

